from pyspark import SparkContext

# Set up SparkContext object
sc = SparkContext(appName = 'Lab1_Ex1')

# Upload data file
temps = sc.textFile('BDA/input/temperature-readings.csv')

# Split each line into a list of strings
obs = temps.map(lambda line: line.split(";"))

# Create tuple with year as key and temp as value
year_temps = obs.map(lambda x: (x[1][0:4], (x[0], float(x[3]))))

# Filter out observations before 1950 and after 2014
year_temps = year_temps.filter(lambda x: int(x[0]) >= 1950 and int(x[0]) <= 2014)

# Find and return maximum temperatures for each year
# max_temps = year_temps.reduceByKey(lambda a, b: float(a[1]) if float(a[1]) >= float(b[1]) else float(b[1]))

# Find and return minimum temperatures for each year
min_temps = year_temps.reduceByKey(lambda a, b: a if a[1] <= b[1] else b)

# Sort tuples in descending order by temperature
# sort_max = max_temps.sortBy(keyfunc = lambda x: x[1][1], ascending = False)
sort_min = min_temps.sortBy(keyfunc = lambda x: x[1][1], ascending = False)

# Map output tuple
output = sort_min.map(lambda x: (int(x[0]), int(x[1][0]), x[1][1]))

# Export max temperatures in a text file
output.saveAsTextFile('BDA/output/BDA_Lab1_Ex1_Output')


